const translations = {
  ...bidiTranslations,
  ...reverseTranslations,
  ...directArabicTranslations,
};

const getInitialLanguage = () => {
  try {
    const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (stored === "en" || stored === "ar") return stored;
  } catch {
    // ignore storage failures
  }

  if (typeof navigator !== "undefined") {
    const browserLanguage = navigator.language || "";
    if (browserLanguage.toLowerCase().startsWith("en")) return "en";
  }

  return "ar";
};

export const useLanguage = () => useContext(LanguageContext);

export const LanguageProvider = ({ children }) => {
  const [language, setLanguageState] = useState(getInitialLanguage);
  const isArabic = language === "ar";

  const setLanguage = (nextLanguage) => {
    if (nextLanguage === "en" || nextLanguage === "ar") {
      setLanguageState(nextLanguage);
      return;
    }

    setLanguageState("ar");
  };

  const toggleLanguage = () => {
    setLanguageState((current) => (current === "ar" ? "en" : "ar"));
  };

  useEffect(() => {
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
    } catch {
      // ignore storage failures
    }

    document.documentElement.lang = language;
    document.documentElement.dir = isArabic ? "rtl" : "ltr";
  }, [language, isArabic]);

  const t = useCallback((text) => {
    if (typeof text !== "string") return text;

    const trimmed = text.trim();
    if (!trimmed) return text;

    const sourceIsArabic = /[\u0600-\u06FF]/.test(trimmed);
    if (isArabic === sourceIsArabic) {
      return trimmed;
    }

    return translations[trimmed] ?? trimmed;
  }, [isArabic]);

  const value = useMemo(
    () => ({
      language,
      isArabic,
      setLanguage,
      toggleLanguage,
      t,
    }),
    [language, isArabic, t]
  );

  return (
    <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
  );
};
